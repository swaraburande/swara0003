# Actual output
y = 1

# Initial weight
w = 0.5

# Learning rate
lr = 0.1

# Prediction
prediction = x * w

# Error
error = y - prediction

# Gradient
gradient = -2 * x * error

# Update weight
w = w - lr * gradient

print("Prediction:", prediction)
print("Error:", error)
print("Gradient:", gradient)
print("Updated Weight:", w)

