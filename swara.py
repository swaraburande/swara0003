import numpy as np

# Input
x = np.array([2, 3])

# Weights
w = np.array([0.5, 0.2])

# Bias
b = 1

# Weighted sum
z = np.dot(x, w) + b

# Step activation
if z >= 0:
    output = 1
else:
    output = 0

print("Input:", x)
print("Weights:", w)
print("Bias:", b)
print("Weighted Sum:", z)
print("Output:", output)

